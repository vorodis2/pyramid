import assert from 'node:assert/strict';
import * as THREE from 'three';
import { BStatus } from '../src/pirDiv/piramidka/Blocks/BStatus.js';

globalThis.window = { param: { color: '#008cba', colorActive: '#ff0000' } };

const content3D = new THREE.Group();
const mesh = new THREE.Mesh(new THREE.BoxGeometry(), new THREE.MeshBasicMaterial());
mesh.position.set(1, 2, 3);
mesh.rotation.y = 0.7;
const nested = new THREE.Group();
nested.position.set(2, 1, -1);
const child = new THREE.Mesh(new THREE.SphereGeometry(), new THREE.MeshBasicMaterial());
nested.add(child);
mesh.add(nested);
content3D.add(mesh);
const status = new BStatus({ content3D });
assert.equal(status.arrOverlays.length, 0);
status.active = true;
assert.equal(status.arrOverlays.length, 2);
const arrOriginalOverlays = [...status.arrOverlays];
content3D.updateMatrixWorld(true);
for (const overlay of status.arrOverlays) {
  assert.equal(overlay.geometry, overlay.parent.geometry);
  assert.equal(overlay.material.wireframe, true);
  assert.deepEqual(overlay.matrixWorld.elements, overlay.parent.matrixWorld.elements);
  const arrHits = [];
  overlay.raycast({}, arrHits);
  assert.equal(arrHits.length, 0);
}
status.active = false;
assert(status.arrOverlays.every((overlay) => !overlay.visible));
status.active = true;
assert.deepEqual(status.arrOverlays, arrOriginalOverlays, 'Reactivation must reuse overlays');
assert.equal(status.material.color.getHex(), 0xff0000);
assert.equal(status.material.opacity, 0.15);
status.over = true;
assert.equal(status.material.color.getHex(), 0xff0000, 'Selection color takes priority over hover');
status.active = false;
assert.equal(status.material.color.getHex(), 0x008cba);
assert.equal(status.material.opacity, 0.15);
assert(status.arrOverlays.every((overlay) => overlay.visible));
status.over = false;
assert(status.arrOverlays.every((overlay) => !overlay.visible));
status.active = true;
let geometryDisposed = false;
mesh.geometry.addEventListener('dispose', () => { geometryDisposed = true; });
status.refresh();
assert.equal(status.arrOverlays.length, 2, 'Refresh must not duplicate overlays');
assert(arrOriginalOverlays.every((overlay) => overlay.parent === null));
status.dispose();
assert.equal(status.arrOverlays.length, 0);
assert.equal(status.active, false);
assert.equal(geometryDisposed, false, 'Overlay cleanup must preserve original geometry');
mesh.geometry.dispose();
mesh.material.dispose();
child.geometry.dispose();
child.material.dispose();
console.log('PASS: nested wireframes, transforms, reuse, picking and cleanup');
